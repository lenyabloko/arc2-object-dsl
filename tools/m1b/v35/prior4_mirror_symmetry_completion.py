# ------------------------------------------------------------------ helpers
def _bgc(g):
    return CR.background(g)


def _train_bg(train):
    """role-bound value: the background of the training set = CR.background of all training input cells pooled"""
    return CR.background([row for p in train for row in p['input']])


def _roles(G, bg, cache):
    """declared roles on grid G: values {('rank',k): colour} and rank positions {colour: k} (memoised in cache)"""
    r = cache.get('_roles')
    if r is None:
        tal = Counter(v for row in G for v in row if v != bg)
        order = sorted(tal, key=lambda x: (-tal[x], x))
        r = cache['_roles'] = ({('rank', k): CR.rank_colour(G, k, bg) for k in CR.RANKS},
                               {v: i + 1 for i, v in enumerate(order)})
    return r


def _rname(spec):
    return 'none' if spec is None else ('novel' if spec[0] == 'novel' else 'rank%d' % spec[1])


def _rv(spec, G, bg, v, cache):
    """a role value: 'bg', 'src' (the source cell's colour), ('novel', c) fixed by training, ('rank', k) on G"""
    if spec == 'bg':
        return bg
    if spec == 'src':
        return v
    if spec[0] == 'novel':
        return spec[1]
    return _roles(G, bg, cache)[0].get(spec)


_CC = {}


def _comps(g, bg, conn=8):
    """memoised on grid content (callers never mutate the returned cell lists)"""
    key = (tuple(map(tuple, g)), bg, conn)
    res = _CC.get(key)
    if res is None:
        if len(_CC) > 256:
            _CC.clear()
        res = _CC[key] = _comps_raw(g, bg, conn)
    return res


def _comps_raw(g, bg, conn):
    H, W = len(g), len(g[0])
    if conn == 8:
        nb = [(a, b) for a in (-1, 0, 1) for b in (-1, 0, 1) if a or b]
    else:
        nb = [(1, 0), (-1, 0), (0, 1), (0, -1)]
    seen = set()
    out = []
    for r in range(H):
        for c in range(W):
            if g[r][c] == bg or (r, c) in seen:
                continue
            seen.add((r, c))
            st, cells = [(r, c)], []
            while st:
                y, x = st.pop()
                cells.append((y, x))
                for dy, dx in nb:
                    q = (y + dy, x + dx)
                    if 0 <= q[0] < H and 0 <= q[1] < W and q not in seen and g[q[0]][q[1]] != bg:
                        seen.add(q)
                        st.append(q)
            out.append(cells)
    return out


def _mono_comps(g, col):
    H, W = len(g), len(g[0])
    seen, out = set(), []
    for r in range(H):
        for c in range(W):
            if g[r][c] != col or (r, c) in seen:
                continue
            seen.add((r, c))
            st, cells = [(r, c)], []
            while st:
                y, x = st.pop()
                cells.append((y, x))
                for q in ((y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)):
                    if 0 <= q[0] < H and 0 <= q[1] < W and q not in seen and g[q[0]][q[1]] == col:
                        seen.add(q)
                        st.append(q)
            out.append(cells)
    return out


def _refl(p, m):
    ax, k = m
    r, c = p
    if ax == 'v':
        return (r, k - c)
    if ax == 'h':
        return (k - r, c)
    if ax == 't':
        return (c + k, r - k)
    if ax == 'a':
        return (k - c, k - r)
    if ax == 'r':                       # quarter turn clockwise about the doubled centre k
        return ((k[0] + 2 * c - k[1]) // 2, (k[1] - 2 * r + k[0]) // 2)
    return (k[0] - r, k[1] - c)


def _rfn(m):
    ax, k = m
    if ax == 'v':
        return lambda r, c: (r, k - c)
    if ax == 'h':
        return lambda r, c: (k - r, c)
    if ax == 't':
        return lambda r, c: (c + k, r - k)
    if ax == 'a':
        return lambda r, c: (k - c, k - r)
    if ax == 'r':
        return lambda r, c: ((k[0] + 2 * c - k[1]) // 2, (k[1] - 2 * r + k[0]) // 2)
    return lambda r, c: (k[0] - r, k[1] - c)


def _orbit(p, ms, H, W):
    if len(ms) == 1 and ms[0][0] != 'r':          # an involution: the orbit is p and its one image
        q2 = _refl(p, ms[0])
        if q2 != p and -H <= q2[0] < 2 * H and -W <= q2[1] < 2 * W:
            return {p: None, q2: ms[0][0]}
        return {p: None}
    orb = {p: None}
    st = [p]
    while st and len(orb) < 16:
        q = st.pop()
        for m in ms:
            q2 = _refl(q, m)
            if q2 not in orb and -H <= q2[0] < 2 * H and -W <= q2[1] < 2 * W:
                orb[q2] = orb[q] or m[0]
                st.append(q2)
    return orb


def _is_sym(cells, g, m):
    s = set(cells)
    for p in cells:
        q = _refl(p, m)
        if q not in s or g[p[0]][p[1]] != g[q[0]][q[1]]:
            return False
    return True


def _unit(S, M, ms, mc=None):
    return {'S': S, 'M': M, 'ms': ms, 'mc': mc}


